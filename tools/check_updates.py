"""Check public Rebuffed releases and write login hints. Never install updates."""
import argparse
import concurrent.futures
import json
import os
from pathlib import Path
import re
import time
import urllib.request

ADDONS = ('RebuffedHealbot', 'RebuffedItemLevel', 'RebuffedRaidMarket', 'RebuffedUpgrade')
VERSION = re.compile(r'^\d{1,6}\.\d{1,6}\.\d{1,6}$')


def release_version(data):
    if not isinstance(data, dict) or data.get('draft') or data.get('prerelease'):
        raise ValueError('Not a stable release')
    tag = data.get('tag_name', '')
    if not isinstance(tag, str):
        raise ValueError('Invalid release tag')
    value = tag[1:] if tag.startswith('v') else tag
    if not VERSION.fullmatch(value):
        raise ValueError('Expected a major.minor.patch release tag')
    return value


def fetch_release(name):
    if name not in ADDONS:
        raise ValueError('Unknown addon')
    request = urllib.request.Request(
        f'https://api.github.com/repos/Derfavo/{name}/releases/latest',
        headers={'User-Agent': 'RebuffedUpdateCheck/1.0', 'Accept': 'application/vnd.github+json'})
    with urllib.request.urlopen(request, timeout=8) as response:
        raw = response.read(1024 * 1024 + 1)
        if len(raw) > 1024 * 1024:
            raise ValueError('Release response too large')
        return release_version(json.loads(raw))


def write_status(game_path, name, status):
    if name not in ADDONS or not VERSION.fullmatch(status.get('latest', '')):
        raise ValueError('Invalid update status')
    folder = game_path / 'Interface' / 'AddOns' / name
    if not (folder / f'{name}.toc').is_file():
        return
    target = folder / 'VersionStatus.lua'
    content = ('-- Generated by the external update checker. No addon code is downloaded.\n'
               '_G.RebuffedUpdateStatus = _G.RebuffedUpdateStatus or {}\n'
               f'_G.RebuffedUpdateStatus["{name}"] = {{latest = "{status["latest"]}", '
               f'checkedAt = {int(status["checkedAt"])}}}\n')
    if target.exists() and target.read_text(encoding='utf-8') == content:
        return
    temporary = target.with_suffix('.lua.tmp')
    temporary.write_text(content, encoding='utf-8', newline='\n')
    temporary.replace(target)


def run(game_path, cache_path, fetch=fetch_release, now=None):
    now = int(time.time() if now is None else now)
    if not (game_path / 'Interface' / 'AddOns').is_dir():
        raise ValueError('Choose the WoW folder containing Interface/AddOns')
    try:
        cache = json.loads(cache_path.read_text(encoding='utf-8'))
        if not isinstance(cache, dict):
            cache = {}
    except (OSError, ValueError):
        cache = {}
    installed = [name for name in ADDONS if (game_path / 'Interface' / 'AddOns' / name / f'{name}.toc').is_file()]
    pending = []
    for name in installed:
        old = cache.get(name)
        if not isinstance(old, dict):
            old = {}
        age = now - old.get('checkedAt', 0) if isinstance(old.get('checkedAt', 0), (int, float)) else 999999
        if not VERSION.fullmatch(str(old.get('latest', ''))) or not 0 <= age < 900:
            pending.append(name)
    errors = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as executor:
        futures = {executor.submit(fetch, name): name for name in pending}
        for future in concurrent.futures.as_completed(futures):
            name = futures[future]
            try:
                version = future.result()
                if not VERSION.fullmatch(version):
                    raise ValueError('Invalid version')
                cache[name] = {'latest': version, 'checkedAt': now}
            except Exception as error:
                errors.append(f'{name}: {type(error).__name__}')
    for name in installed:
        status = cache.get(name)
        if isinstance(status, dict) and VERSION.fullmatch(str(status.get('latest', ''))) and isinstance(status.get('checkedAt'), int):
            write_status(game_path, name, status)
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    temporary = cache_path.with_suffix('.tmp')
    temporary.write_text(json.dumps(cache, indent=2), encoding='utf-8')
    temporary.replace(cache_path)
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--game-path', required=True, type=Path)
    parser.add_argument('--cache-path', type=Path, default=Path(os.environ.get('LOCALAPPDATA', str(Path.home()))) / 'RebuffedAddons' / 'release-cache.json')
    args = parser.parse_args()
    try:
        errors = run(args.game_path.resolve(), args.cache_path)
    except Exception as error:
        errors = [type(error).__name__ + ': ' + str(error)]
    log = args.cache_path.parent / 'update-check.log'
    log.parent.mkdir(parents=True, exist_ok=True)
    log.write_text(time.strftime('%Y-%m-%d %H:%M:%S') + '\n' + ('\n'.join(errors) if errors else 'OK') + '\n', encoding='utf-8')
    return 1 if errors else 0


if __name__ == '__main__':
    raise SystemExit(main())
